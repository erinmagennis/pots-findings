#!/usr/bin/env python3
"""verify_site_v12.py — assert the site projection against the released packages, and that no count in site copy is hand-typed.

Checks (each failure names what/got/expected/source):
  1. meta.counts == validation/v12_golden_facts.json counts (generated by build_v12_projection.py from packages/*/data)
  2. golden findings == sum of packages/*/qa/package_stats.json findings (independent source: the package verifier's own stats)
  3. findings_facets: n, n_shards, every column length == n, every code < dict size, paper index < papers rows
  4. text/detail shards contiguous, lengths match, detail has the 12 contract keys
  5. papers.json fields == contract, rows == golden; entities.json n == golden
  6. discovery tables carry the columns page-discover.js reads
  7. emb/manifest.json total_rows == n and every shard file has rows*dims bytes; quant_params has dims entries
  8. NUMBERS CHECK: no comma-formatted number >= 1,000 and no bare integer >= 1000 (except years 1900-2099) appears in site/*.html or
     site/js/*.js outside <!--n:KEY-->…<!--/n--> markers, code comments, CSS/SVG numerics and an explicit allowlist
  9. markers in static HTML equal the current meta value (apply_counts.py was run)
 10. CHECKSUMS.txt covers every file under site/ and matches
 11. PAPER COUNT: meta.counts.papers == distinct pmids across packages/*/data/tier*_findings (read directly, not via the projection)
 12. PAPER FLAGS: every pmid in paper_flags.json is a site paper; findings from exclude-flagged papers are left out of the
     default facet-based counts (findings_default / excluded_findings / retracted_findings recomputed from facets.p + flags),
     no Signals table (associations, contradictions, understudied, convergence, null results) cites an exclude-flagged paper,
     and data.js applyFilters carries the default exclusion
--self-test plants failures (count, marker, hand-typed number, a flag on a non-site paper, a wrong default count) and requires all to be caught.
"""
import argparse, copy, csv, glob, gzip, hashlib, json, os, re, sys
from pathlib import Path

DETAIL_KEYS = {"start", "end", "quote", "quant", "eff", "path", "lim", "fut", "npart", "comp", "symp", "treat", "sec", "ont"}
PAPER_FIELDS = ["pmid", "first_author", "authors", "author_count", "journal", "year", "doi_url", "pubmed_url", "pmc_url", "citation_short", "n_findings", "is_open_access", "cited_by_count", "title"]
DISCOVERY = {"associations.json": {"entity_a", "entity_b", "n_papers_both", "expected_papers_both", "lift", "jaccard", "q_bh", "significant_fdr05", "cross_kind", "assoc_score_recomputed", "pmids"},
             "understudied.json": {"canonical_entity", "condition", "direction", "n_papers", "n_findings", "best_tier", "case_report_only", "is_thin", "replication_score", "source_literatures", "pmids"},
             "contradictions.json": {"canonical_entity", "condition", "conflict_type", "side_A_direction", "n_papers_A", "pmids_A", "side_B_direction", "n_papers_B", "pmids_B", "source_literatures"},
             "null_results.json": {"canonical_pmid", "null_class", "condition", "evidence_tier", "provenance_quote_trunc", "canonical_entity", "entity", "treatment_class", "year"},
             "convergence.json": {"canonical_entity", "concordant_direction", "n_source_literatures", "source_literatures", "n_papers", "n_findings", "best_tier"}}
# numbers that legitimately appear in code/copy and are not corpus counts
ALLOW = {"2023-06-01", "1200", "6000", "0001", "9999", "1000", "1e9", "2048", "4096", "8080", "3000", "65535", "1024", "1800", "1900", "2099", "120000"}  # 120000 = embedding worker timeout (ms) in search.js
MARKER = re.compile(r"<!--n:([a-z_0-9]+)-->(.*?)<!--/n-->", re.S)


def _no_nan(c): raise ValueError(f"non-standard JSON constant {c} (browsers reject NaN/Infinity)")
def rj(p): return json.load(open(p, encoding="utf-8"), parse_constant=_no_nan)
def add(f, what, got, exp, src):
    if got != exp: f.append((what, got, exp, src))


def strip_code_noise(text, is_js):
    if is_js:
        text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S); text = re.sub(r"(^|[^:])//[^\n]*", r"\1", text)
    else:
        text = re.sub(r"<!--(?!n:|/n).*?-->", " ", text, flags=re.S); text = re.sub(r"<(script|style)[^>]*>.*?</\1>", " ", text, flags=re.S)
        text = re.sub(r"<svg.*?</svg>", " ", text, flags=re.S)
    text = MARKER.sub(" ", text)
    text = re.sub(r"#[0-9a-fA-F]{3,8}\b", " ", text)                      # colours
    text = re.sub(r"\b\d+(\.\d+)?(px|em|rem|ms|s|%|vh|vw|deg)\b", " ", text)  # css numerics
    text = re.sub(r"(rgba?|hsla?)\([^)]*\)", " ", text)
    text = re.sub(r"https?://\S+", " ", text); text = re.sub(r"\b[0-9a-f]{12,}\b", " ", text)
    return text


def numbers_check(site, failures):
    hits = []
    for p in sorted(glob.glob(f"{site}/*.html") + glob.glob(f"{site}/js/*.js")):
        raw = open(p, encoding="utf-8").read(); t = strip_code_noise(raw, p.endswith(".js"))
        for m in re.finditer(r"(?<![\w.\-(,])([1-9]\d{0,2}(?:,\d{3})+|\d{4,})(?![\w.\-])", t):
            v = m.group(1)
            if v in ALLOW: continue
            if "," not in v and 1900 <= int(v) <= 2099: continue
            hits.append(f"{os.path.relpath(p, site)}: {v}")
    if hits: failures.append(("hand-typed numbers in site copy", hits[:25] + ([f"... {len(hits) - 25} more"] if len(hits) > 25 else []), [], "numbers must come from meta.json or <!--n:KEY--> markers"))
    return len(hits)


def markers_check(site, meta, cov, failures):
    src = dict(cov); src.update(meta["counts"]); src["version"] = meta["version"]
    def fmt(v): return f"{v:,}" if isinstance(v, int) else str(v)
    n = 0
    for p in sorted(glob.glob(f"{site}/*.html")):
        for k, val in MARKER.findall(open(p, encoding="utf-8").read()):
            n += 1
            if k not in src: failures.append((f"marker {k}", "no such meta key", "known key", os.path.basename(p))); continue
            add(failures, f"marker {k} in {os.path.basename(p)}", val, fmt(src[k]), "apply_counts.py not run")
    return n


def package_pmids(root):
    """distinct pmids over the released findings files, read directly (pyarrow when present, else the shipped .csv.gz)."""
    out = set(); files = sorted(glob.glob(str(root / "packages" / "*" / "data" / "tier*_findings.parquet")))
    try:
        import pyarrow.parquet as pq
        for fp in files: out.update(str(x) for x in pq.read_table(fp, columns=["pmid"]).column("pmid").to_pylist() if x is not None)
        return out, len(files)
    except ImportError:
        csv.field_size_limit(1 << 30); files = sorted(glob.glob(str(root / "packages" / "*" / "data" / "tier*_findings.csv.gz")))
        for fp in files:
            with gzip.open(fp, "rt", encoding="utf-8", newline="") as fh:
                for r in csv.DictReader(fh): out.add(str(int(float(r["pmid"]))) if r.get("pmid") else None)
        out.discard(None); return out, len(files)


def flags_check(data, P, F, C, failures, flags_override=None):
    """paper flags: pmids are site papers; default exclusion matches meta; no Signals table cites an excluded paper."""
    n = 0; pf = flags_override if flags_override is not None else rj(data / "paper_flags.json")
    pi = P["fields"].index("pmid"); site_pm = [str(r[pi]) for r in P["rows"]]; site_set = set(site_pm)
    bad = sorted(set(pf["flags"]) - site_set); add(failures, "paper_flags pmids not site papers", bad[:10], [], "paper_flags.json vs papers.json"); n += 1
    excl = {p for p, L in pf["flags"].items() if any(x.get("u") == "exclude" for x in L)}
    retr = {p for p, L in pf["flags"].items() if any(x.get("f") in ("retracted", "partially_retracted") for x in L)}
    ex_idx = {i for i, p in enumerate(site_pm) if p in excl}; rt_idx = {i for i, p in enumerate(site_pm) if p in retr}
    col = F["cols"]["p"]; n_ex = sum(1 for x in col if x in ex_idx); n_rt = sum(1 for x in col if x in rt_idx)
    add(failures, "default findings (facets minus exclude-flagged papers)", F["n"] - n_ex, C.get("findings_default"), "meta.counts.findings_default")
    add(failures, "excluded_findings", n_ex, C.get("excluded_findings"), "facets.p + paper_flags.json")
    add(failures, "retracted_findings", n_rt, C.get("retracted_findings"), "facets.p + paper_flags.json")
    add(failures, "excluded_papers", len(excl), C.get("excluded_papers"), "paper_flags.json"); n += 4
    for fk in pf.get("labels", {}):
        add(failures, f"counts.flag_{fk}", sum(1 for L in pf["flags"].values() if any(x["f"] == fk for x in L)), C.get(f"flag_{fk}"), "paper_flags.json"); n += 1
    hits = []
    for fn, keys in [("associations.json", ["pmids"]), ("contradictions.json", ["pmids_A", "pmids_B"]), ("understudied.json", ["pmids"])]:
        for r in rj(data / fn)["rows"]:
            for k in keys: hits += [f"{fn}:{p}" for p in (r.get(k) or []) if str(p) in excl]
    NI = rj(data / "null_results.json"); ci = NI["fields"].index("canonical_pmid")
    for sh in NI["shards"]: hits += [f"{sh['file']}:{r[ci]}" for r in rj(data / sh["file"])["rows"] if str(r[ci]) in excl]
    add(failures, "Signals tables citing exclude-flagged papers", hits[:10], [], "projection must drop recommended_use=exclude papers"); n += 1
    js = open(data.parent / "js" / "data.js", encoding="utf-8").read()
    add(failures, "data.js applyFilters default exclusion", bool(re.search(r"function applyFilters[\s\S]*?excludePaper", js)), True, "site/js/data.js"); n += 1
    return n


def check(root: Path, site: Path, meta_override=None, html_override=None, flags_override=None):
    f = []; data = site / "data"; checks = 0
    meta = copy.deepcopy(meta_override) if meta_override else rj(data / "meta.json"); C = meta["counts"]
    golden = rj(root / "validation" / "v12_golden_facts.json")
    for k, v in golden["counts"].items():
        if not isinstance(v, dict): add(f, f"counts.{k}", C.get(k), v, "golden facts"); checks += 1
    pkg_sum = 0
    for ps in glob.glob(str(root / "packages" / "*" / "qa" / "package_stats.json")): pkg_sum += rj(ps)["findings"]
    add(f, "findings vs packages/*/qa/package_stats.json", golden["counts"]["findings"], pkg_sum, "independent package stats"); checks += 1
    F = rj(data / "findings_facets.json"); n = F["n"]
    add(f, "facets.n", n, C["findings"], "meta"); add(f, "n_shards", F["n_shards"], -(-n // F["shard_rows"]), "ceil"); checks += 2
    for k, col in F["cols"].items():
        add(f, f"col {k} length", len(col), n, "facets"); checks += 1
        if k in F["dicts"] and col: add(f, f"col {k} max code", max(col) < len(F["dicts"][k]), True, "dict bounds"); checks += 1
    P = rj(data / "papers.json"); add(f, "papers.fields", P["fields"], PAPER_FIELDS, "contract"); add(f, "papers rows", len(P["rows"]), golden["papers_rows"], "golden"); checks += 2
    add(f, "paper index bound", max(F["cols"]["p"]) < len(P["rows"]), True, "facets.p"); checks += 1
    pk, nfiles = package_pmids(root)
    add(f, "papers vs distinct pmids in packages/*/data/tier*_findings", C["papers"], len(pk), f"{nfiles} package findings files"); add(f, "package findings files", nfiles, 5, "packages")
    add(f, "papers.json pmids == package pmids", set(str(r[P["fields"].index("pmid")]) for r in P["rows"]) == pk, True, "packages"); checks += 3
    checks += flags_check(data, P, F, C, f, flags_override)
    for s in range(F["n_shards"]):
        a, b = s * F["shard_rows"], min((s + 1) * F["shard_rows"], n)
        T = rj(data / f"text_{s:02d}.json"); Dd = rj(data / f"detail_{s:02d}.json")
        add(f, f"text_{s:02d} range", (T["start"], T["end"], len(T["t"])), (a, b, b - a), "shards"); add(f, f"detail_{s:02d} keys", set(Dd) >= DETAIL_KEYS, True, "contract")
        add(f, f"detail_{s:02d} lengths", all(len(Dd[k]) == b - a for k in DETAIL_KEYS - {"start", "end"}), True, "shards"); checks += 3
    E = rj(data / "entities.json"); add(f, "entities.n", E["n"], golden["entities_rows"], "golden"); add(f, "entities list", len(E["entities"]), E["n"], "self"); checks += 2
    for fn, cols in DISCOVERY.items():
        d = rj(data / fn)
        if fn == "null_results.json":                     # index + column-oriented shards
            add(f, "null_results fields", cols <= set(d["fields"]), True, "page-discover.js"); total = 0
            for sh in d["shards"]:
                S_ = rj(data / sh["file"]); total += len(S_["rows"])
                add(f, f"{sh['file']} row width", all(len(r) == len(d["fields"]) for r in S_["rows"]), True, "fields")
                add(f, f"{sh['file']} range", (S_["start"], S_["end"], len(S_["rows"])), (sh["start"], sh["end"], sh["end"] - sh["start"]), "index"); checks += 2
            add(f, "null_results n", total, d["n"], "shards"); add(f, "null_results vs meta", d["n"], C["null_results"], "meta"); checks += 3
            continue
        rows = d.get("rows", [])
        add(f, f"{fn} n", d.get("n"), len(rows), "self"); checks += 1
        if rows: add(f, f"{fn} columns", cols <= set(rows[0]), True, "page-discover.js"); checks += 1
    for listed, total in [("associations", "associations_total"), ("contradictions", "contradictions_total"), ("understudied", "understudied_total"), ("convergence", "convergence_total")]:
        add(f, f"{total} >= {listed}", C[total] >= C[listed], True, "export cap must not exceed the true count"); checks += 1
    man = rj(data / "emb" / "manifest.json"); qp = rj(data / "emb" / "quant_params.json")
    add(f, "emb total_rows", man["total_rows"], n, "manifest"); add(f, "quant dims", (len(qp["qmin"]), len(qp["scale"])), (man["dims"], man["dims"]), "quant_params"); checks += 2
    for sh in man["shards"]:
        add(f, f"emb shard {sh['file']} bytes", os.path.getsize(data / "emb" / sh["file"]), sh["rows"] * man["dims"], "manifest"); checks += 1
    cov = F["coverage"]
    checks += numbers_check(site if html_override is None else html_override, f) or 1
    checks += markers_check(site if html_override is None else html_override, meta, cov, f)
    # checksums
    ck = site / "CHECKSUMS.txt"
    if ck.exists():
        listed = {}
        for line in open(ck, encoding="utf-8"):
            if line.strip(): h, rel = line.strip().split(None, 1); listed[rel] = h
        for p in sorted(x for x in site.rglob("*") if x.is_file() and x != ck):
            rel = p.relative_to(site).as_posix(); checks += 1
            if rel not in listed: f.append((f"CHECKSUMS.txt missing {rel}", None, "listed", "checksums")); continue
            add(f, f"checksum {rel}", hashlib.sha256(p.read_bytes()).hexdigest(), listed[rel], "CHECKSUMS.txt")
    else: f.append(("CHECKSUMS.txt", "missing", "present", "checksums"))
    return f, checks


def report(f, checks, label=""):
    if f:
        print(f"FAIL{label}: {len(f)} failures across {checks:,} assertions")
        for what, got, exp, src in f: print(f"\n  {what}\n    got: {str(got)[:400]}\n    expected: {str(exp)[:200]}\n    source: {src}")
        return 1
    print(f"PASS{label}: {checks:,} assertions"); return 0


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--root", default="."); ap.add_argument("--site", default="site"); ap.add_argument("--self-test", action="store_true")
    a = ap.parse_args(); root = Path(a.root).resolve(); site = root / a.site
    f, checks = check(root, site); r = report(f, checks)
    if r or not a.self_test: return r
    import shutil, tempfile
    bad = rj(site / "data" / "meta.json"); bad["counts"]["papers"] += 7; bad["counts"]["findings"] = 1; bad["counts"]["findings_default"] += 1
    f1, _ = check(root, site, meta_override=bad); caught = {x[0] for x in f1}
    tmp = Path(tempfile.mkdtemp()); shutil.copytree(site, tmp / "site", ignore=shutil.ignore_patterns("data", "vendor"))
    (tmp / "site" / "js").mkdir(exist_ok=True)
    with open(tmp / "site" / "about.html", "a", encoding="utf-8") as fh: fh.write("<p>planted: 73,070 findings from <!--n:papers-->6,244<!--/n--> papers</p>")
    f2 = []; numbers_check(str(tmp / "site"), f2); markers_check(str(tmp / "site"), rj(site / "data" / "meta.json"), rj(site / "data" / "findings_facets.json")["coverage"], f2)
    caught2 = {("hand-typed numbers in site copy" if x[0].startswith("hand-typed") else x[0].split(" in ")[0]) for x in f2}; shutil.rmtree(tmp)
    badf = rj(site / "data" / "paper_flags.json"); badf["flags"]["99999999"] = [{"f": "retracted", "l": "Retracted", "u": "exclude"}]
    f3, _ = check(root, site, flags_override=badf); caught3 = {x[0] for x in f3}
    need = {"counts.papers", "counts.findings", "facets.n", "papers vs distinct pmids in packages/*/data/tier*_findings", "default findings (facets minus exclude-flagged papers)"}
    need2 = {"hand-typed numbers in site copy", "marker papers"}; need3 = {"paper_flags pmids not site papers", "excluded_papers", "counts.flag_retracted"}
    if not (need <= caught and need2 <= caught2 and need3 <= caught3): print(f"SELF-TEST FAIL: caught {sorted(caught)} / {sorted(caught2)} / {sorted(caught3)}"); return 1
    print(f"SELF-TEST PASS: caught all {len(need) + len(need2) + len(need3)} planted failures"); return 0


if __name__ == "__main__":
    sys.exit(main())
